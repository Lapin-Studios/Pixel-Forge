"""Bundle Pixel Forge into one classic script so index.html runs by double-clicking.

Browsers refuse to load ES modules (and fetch JSON) from file:// pages, so this script:
  * walks the import graph starting at src/main.js,
  * wraps each module in a function scope (imports become locals, exports a returned object),
  * embeds every worlds/*.json preset,
  * writes dist/pixel-forge.js (loaded by index.html) and dev.html (loads src/ as modules).

Usage:  python build.py        (run after editing anything in src/ or worlds/)
No third-party packages needed.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
ENTRY = "src/main.js"
OUT = "dist/pixel-forge.js"

IMPORT_RE = re.compile(r"""^\s*import\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"]\s*;?""", re.M | re.S)
BARE_IMPORT_RE = re.compile(r"""^\s*import\s*['"]([^'"]+)['"]\s*;?""", re.M)
OTHER_IMPORT_RE = re.compile(r"""^\s*import\s+[\w*]""", re.M)
EXPORT_DECL_RE = re.compile(r"^export\s+(?:async\s+)?(?:const|let|var|function\*?|class)\s+([A-Za-z_$][\w$]*)", re.M)
EXPORT_LIST_RE = re.compile(r"^export\s*\{([^}]*)\}\s*;?[ \t]*$", re.M)
EXPORT_KEYWORD_RE = re.compile(r"^export\s+(?=(?:async\s+)?(?:const|let|var|function|class)\b)", re.M)


def norm(path):
    return os.path.normpath(path).replace("\\", "/")


def resolve(from_file, spec):
    if not spec.startswith("."):
        raise SystemExit(f"{from_file}: only relative imports are supported ({spec})")
    return norm(os.path.join(os.path.dirname(from_file), spec))


def parse_names(block):
    """'a, b as c' -> [('a','a'), ('b','c')]"""
    out = []
    for part in block.split(","):
        part = part.strip()
        if not part:
            continue
        bits = part.split(" as ")
        src = bits[0].strip()
        dst = bits[1].strip() if len(bits) > 1 else src
        out.append((src, dst))
    return out


def load_module(path, modules):
    if path in modules:
        return
    full = os.path.join(ROOT, path)
    if not os.path.isfile(full):
        raise SystemExit(f"Missing module: {path}")
    with open(full, encoding="utf-8") as f:
        code = f.read()
    imports = []
    for m in IMPORT_RE.finditer(code):
        imports.append((resolve(path, m.group(2)), parse_names(m.group(1))))
    for m in BARE_IMPORT_RE.finditer(code):
        imports.append((resolve(path, m.group(1)), []))
    stripped = IMPORT_RE.sub("", code)
    stripped = BARE_IMPORT_RE.sub("", stripped)
    if OTHER_IMPORT_RE.search(stripped):
        raise SystemExit(f"{path}: unsupported import form (use named imports)")
    exports = EXPORT_DECL_RE.findall(stripped)
    for m in EXPORT_LIST_RE.finditer(stripped):
        for src, dst in parse_names(m.group(1)):
            exports.append((src, dst))
    stripped = EXPORT_LIST_RE.sub("", stripped)
    stripped = EXPORT_KEYWORD_RE.sub("", stripped)
    if re.search(r"^\s*export\s", stripped, re.M):
        raise SystemExit(f"{path}: unsupported export form")
    modules[path] = {"code": stripped, "imports": imports, "exports": exports}
    for dep, _ in imports:
        load_module(dep, modules)


def topo_order(modules, entry):
    order, state = [], {}

    def visit(p, stack):
        s = state.get(p)
        if s == 2:
            return
        if s == 1:
            raise SystemExit("Circular import: " + " -> ".join(stack + [p]))
        state[p] = 1
        for dep, _ in modules[p]["imports"]:
            visit(dep, stack + [p])
        state[p] = 2
        order.append(p)

    visit(entry, [])
    return order


def export_entries(exports):
    entries = []
    for e in exports:
        if isinstance(e, tuple):
            src, dst = e
            entries.append(src if src == dst else f"{dst}: {src}")
        else:
            entries.append(e)
    return ", ".join(entries)


def build():
    modules = {}
    load_module(ENTRY, modules)
    order = topo_order(modules, ENTRY)

    worlds = {}
    wdir = os.path.join(ROOT, "worlds")
    for name in sorted(os.listdir(wdir)):
        if name.endswith(".json"):
            with open(os.path.join(wdir, name), encoding="utf-8") as f:
                worlds[f"worlds/{name}"] = json.load(f)

    parts = [
        "/* Pixel Forge — bundled build. Generated by build.py from src/ and worlds/. Do not edit; edit src/ and re-run build.py. */",
        "window.__PIXELFORGE_WORLDS = " + json.dumps(worlds, separators=(",", ":")) + ";",
        "(function () {",
        "'use strict';",
        "const __modules = Object.create(null);",
    ]
    for path in order:
        mod = modules[path]
        lines = [f"\n// ── {path} " + "─" * max(4, 70 - len(path))]
        lines.append(f"__modules[{json.dumps(path)}] = (function () {{")
        for dep, names in mod["imports"]:
            if not names:
                continue
            binds = ", ".join(src if src == dst else f"{src}: {dst}" for src, dst in names)
            for src, _ in names:
                dep_exports = [e if isinstance(e, str) else e[1] for e in modules[dep]["exports"]]
                if src not in dep_exports:
                    raise SystemExit(f"{path}: '{src}' is not exported by {dep}")
            lines.append(f"const {{ {binds} }} = __modules[{json.dumps(dep)}];")
        lines.append(mod["code"].strip("\n"))
        lines.append(f"return {{ {export_entries(mod['exports'])} }};")
        lines.append("})();")
        parts.append("\n".join(lines))
    parts.append("})();\n")

    out_path = os.path.join(ROOT, OUT)
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(parts))

    # dev.html: same page, but loads the unbundled ES modules (needs `python serve.py`).
    with open(os.path.join(ROOT, "index.html"), encoding="utf-8") as f:
        index = f.read()
    tag = '<script src="dist/pixel-forge.js"></script>'
    if tag not in index:
        raise SystemExit("index.html must contain " + tag)
    dev = index.replace(tag, '<script type="module" src="src/main.js"></script>')
    dev = dev.replace("<title>Pixel Forge — Physics Sandbox</title>", "<title>Pixel Forge (dev) — Physics Sandbox</title>")
    with open(os.path.join(ROOT, "dev.html"), "w", encoding="utf-8", newline="\n") as f:
        f.write(dev)

    size = os.path.getsize(out_path)
    print(f"Bundled {len(order)} modules + {len(worlds)} worlds -> {OUT} ({size // 1024} KB)")


if __name__ == "__main__":
    try:
        build()
    except SystemExit as e:
        if e.code not in (None, 0):
            print("Build failed:", e.code, file=sys.stderr)
            sys.exit(1)
